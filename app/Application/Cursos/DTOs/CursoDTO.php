            imagen_banner_url:        $this->imagen_banner_url,
            imagen_alt:               $this->imagen_alt,
            url_video:                $this->url_video,
            url_whatsapp:             $this->url_whatsapp,
            url_whatsapp2:            $this->url_whatsapp2,
            titulo_documento1:        $this->titulo_documento1,
            documento1:               $this->documento1,
            imagenes:                 $this->imagenes,
            inicio_actividades:       $this->inicio_actividades,
            finalizacion_actividades: $this->finalizacion_actividades,
            inicio_inscripciones:     $this->inicio_inscripciones,
            mes_facturacion:          $this->mes_facturacion,
            tipo_honorario:           $this->tipo_honorario,
            id_tipoprograma:          $this->id_tipoprograma,
