        public int     $id_programa,
        public ?string $nombre_programa,
        public ?string $slug,
        public ?string $descripcion,
        public ?string $objetivo,
        public ?string $dirigido,
        public ?string $requisitos,
        public ?string $inversion,
        public ?float  $costo_monto,
        public ?string $creditaje,
        public ?string $nota,
        public ?string $foto,
        public ?string $imagen_banner_url,
        public ?string $imagen_alt,
        public ?string $url_video,
        public ?string $url_whatsapp,
        public ?string $url_whatsapp2,
        public ?string $titulo_documento1,
        public ?string $documento1,
        public array   $imagenes,
        public ?string $inicio_actividades,
        public ?string $finalizacion_actividades,
        public ?string $inicio_inscripciones,
        public ?string $mes_facturacion,
        public ?string $tipo_honorario,
        public ?int    $id_tipoprograma,
        public ?int    $categoria_web_id,
        public ?int    $formulario_id,
        public ?int    $area_id,
        public ?int    $id_plan,
        public ?int    $id_plandoc,
        public ?int    $id_imp,
        public ?int    $convenio_id,
        public ?int    $vendedor_id,
        public ?string $vendedor_nombre,
        public int     $estado,
        public ?string $estado_web,
        public bool    $destacado,
        public int     $orden,
        public ?string $meta_titulo,
        public ?string $meta_descripcion,
        public ?string $mensaje_exito,
        public ?string $fecha_publicacion,
        public ?string $fecha_reg,
        public ?string $updated_at,
        public ?string $plan_titulo,
        public ?float  $plan_costo,
        public ?int    $plan_nro_cuotas,
        public ?float  $plan_costo_por_cuota,
        public array   $cuotas,
        public ?int    $total_inscritos = null,
        public ?float  $total_recaudado = null,
        public ?array  $tareas_catalogo_ids = null,
