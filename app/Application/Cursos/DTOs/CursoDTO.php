    public static function fromModel(object $m): self
    {
        return new self(
            id_programa:              (int) $m->id_programa,
            nombre_programa:          $m->nombre_programa ?? null,
            slug:                     $m->slug ?? null,
            descripcion:              $m->descripcion ?? null,
            objetivo:                 $m->objetivo ?? null,
            dirigido:                 $m->dirigido ?? null,
            requisitos:               $m->requisitos ?? null,
            inversion:                $m->inversion ?? null,
            costo_monto:              isset($m->costo_monto) && $m->costo_monto !== null ? (float) $m->costo_monto : null,
            creditaje:                $m->creditaje ?? null,
            nota:                     $m->nota ?? null,
            foto:                     $m->foto ?? null,
            imagen_banner_url:        $m->imagen_banner_url ?? null,
            imagen_alt:               $m->imagen_alt ?? null,
            url_video:                $m->url_video ?? null,
            url_whatsapp:             $m->url_whatsapp ?? null,
            url_whatsapp2:            $m->url_whatsapp2 ?? null,
            titulo_documento1:        $m->titulo_documento1 ?? null,
            documento1:               $m->documento1 ?? null,
            imagenes:                 self::normalizarImagenes($m->imagenes ?? null),
            inicio_actividades:       $m->inicio_actividades ? (string) $m->inicio_actividades : null,
            finalizacion_actividades: $m->finalizacion_actividades ? (string) $m->finalizacion_actividades : null,
            inicio_inscripciones:     $m->inicio_inscripciones ? (string) $m->inicio_inscripciones : null,
            mes_facturacion:          $m->mes_facturacion ?? null,
            tipo_honorario:           $m->tipo_honorario ?? null,
            id_tipoprograma:          $m->id_tipoprograma ? (int) $m->id_tipoprograma : null,
            categoria_web_id:         $m->categoria_web_id ? (int) $m->categoria_web_id : null,
            formulario_id:              $m->formulario_id ? (int) $m->formulario_id : null,
            area_id:                  $m->area_id ? (int) $m->area_id : null,
            id_plan:                  $m->id_plan ? (int) $m->id_plan : null,
            id_plandoc:               $m->id_plandoc ? (int) $m->id_plandoc : null,
            id_imp:                   $m->id_imp ? (int) $m->id_imp : null,
            convenio_id:              $m->convenio_id ? (int) $m->convenio_id : null,
            vendedor_id:              ($m->vendedor_id ?? null) ? (int) $m->vendedor_id : null,
            vendedor_nombre:          ($m->vendedor_nombre ?? null) ?: null,
            estado:                   (int) ($m->estado ?? 1),
            estado_web:               $m->estado_web ?? 'borrador',
            destacado:                (bool) ($m->destacado ?? false),
            orden:                    (int) ($m->orden ?? 0),
            meta_titulo:              $m->meta_titulo ?? null,
            meta_descripcion:         $m->meta_descripcion ?? null,
            mensaje_exito:            $m->mensaje_exito ?? null,
            fecha_publicacion:        $m->fecha_publicacion ? (string) $m->fecha_publicacion : null,
            fecha_reg:                $m->fecha_reg ? (string) $m->fecha_reg : null,
            updated_at:               ($m->updated_at ?? null) ? (string) $m->updated_at : null,
            plan_titulo:              $m->plan_titulo ?? ($m->plan_titulo_alt ?? null),
            plan_costo:               isset($m->plan_costo) && $m->plan_costo !== null ? (float) $m->plan_costo : null,
            plan_nro_cuotas:          isset($m->plan_nro_cuotas) && $m->plan_nro_cuotas !== null ? (int) $m->plan_nro_cuotas : null,
            plan_costo_por_cuota:     isset($m->plan_costo_cuota) && $m->plan_costo_cuota !== null ? (float) $m->plan_costo_cuota : null,
            cuotas:                   [],
            total_inscritos:          isset($m->total_inscritos) ? (int) $m->total_inscritos : null,
            total_recaudado:          isset($m->total_recaudado) ? (float) $m->total_recaudado : null,
            tareas_catalogo_ids:      $m->tareas_catalogo_ids ?? null,
        );
    }

    private static function normalizarImagenes(mixed $valor): array
    {
        if (is_array($valor)) {
            return $valor;
        }
        if (is_string($valor)) {
            $decoded = json_decode($valor, true);
            return is_array($decoded) ? $decoded : [];
        }
        return [];
    }
}
